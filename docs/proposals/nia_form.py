def font(run, size=10, bold=False, color=INK, name='맑은 고딕'):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = name
    # ⚠️ 한글은 eastAsia 를 따로 안 정하면 워드가 다른 글꼴로 그린다
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)


def para(doc, text='', size=10, bold=False, color=INK, align=None,
         before=0, after=4, indent=0):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = 1.4
    if indent: p.paragraph_format.left_indent = Cm(indent)
    if align: p.alignment = align
    if text:
        font(p.add_run(text), size, bold, color)
    return p


def head(doc, text, size=13):
    p = para(doc, text, size, True, BLUE, before=14, after=6)
    return p


def sub(doc, text):
    return para(doc, text, 11, True, INK, before=10, after=4)


def note(doc, text):
    return para(doc, '※ ' + text, 9, False, GRAY, after=6)


def table(doc, rows, widths=None, headrow=False):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for ri, row in enumerate(rows):
        for ci, cell in enumerate(row):
            c = t.cell(ri, ci)
            c.text = ''
            p = c.paragraphs[0]
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            bold = (headrow and ri == 0) or (ci == 0 and not headrow)
            col = GRAY if cell == FILL else INK
            font(p.add_run(str(cell)), 9.5, bold, col)
            if widths and ci < len(widths):
                c.width = Cm(widths[ci])
    return t


def bullets(doc, items, size=10, indent=0.5):
    for it in items:
        p = para(doc, '· ' + it, size, indent=indent, after=3)
    return doc


